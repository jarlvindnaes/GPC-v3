// Passenger-only hubs for the filter step: ferry/cruise harbours, passenger stations and leisure airfields, placed
// near freight hubs (deterministic, so the picture is the same on every visit). Illustrative, not real places.
const near = (hubs: [number, number][], count: number, salt: number, spread: number) =>
  Array.from({ length: count }, (_, i) => {
    const [lon, lat] = hubs[Math.floor(Math.abs(Math.sin(i * 12.9898 + salt) * 43758.5453) % hubs.length)];
    const a = Math.sin(i * 78.233 + salt * 3.1) * 43758.5453;
    const b = Math.sin(i * 39.425 + salt * 7.7) * 24634.6345;
    return [lon + ((a - Math.floor(a)) - 0.5) * spread * 2, lat + ((b - Math.floor(b)) - 0.5) * spread] as [number, number];
  });

