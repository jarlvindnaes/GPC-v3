const wobble = (i: number, salt: number) => {
  const x = Math.sin(i * 91.7 + salt * 17.3) * 43758.5453;
  return x - Math.floor(x) - 0.5;
};
export const localLines: LonLat[][] = cities.flatMap(([lon, lat], c) =>
  Array.from({ length: 6 }, (_, k) => {
    let angle = (k / 6) * Math.PI * 2 + wobble(c, k) * 0.8;
    let x = lon + Math.cos(angle) * 0.08;
    let y = lat + Math.sin(angle) * 0.06;
    const points: LonLat[] = [[x, y]];
    const reach = 0.16 + Math.abs(wobble(c * 7 + k, 3)) * 0.18;
    for (let step = 0; step < 6; step++) {
      angle += wobble(c * 31 + k * 7 + step, 5) * 0.9;
      x += Math.cos(angle) * reach;
      y += Math.sin(angle) * reach * 0.72;
      points.push([x, y]);
    }
    return points;
  })
);
